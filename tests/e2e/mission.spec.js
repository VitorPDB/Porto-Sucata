import { test, expect } from '@playwright/test';
import { SOLUTION_SQL } from '../../src/mission.js';

test('mobile mission: inspect, wrong filter, correct query, paused delivery, reload and completion', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 800 });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Inspecionar Lâmpada B', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Lâmpada B' })).toBeVisible();
  await page.getByRole('button', { name: 'Voltar ao cais', exact: true }).click();
  await page.getByRole('button', { name: 'Usar bancada', exact: true }).click();
  await page.getByRole('button', { name: 'Testar seleção' }).click();
  await expect(page.locator('.feedback')).toContainText('A Lâmpada B está quebrada. Acrescente uma condição');
  await expect(page.getByRole('button', { name: 'Enviar drone' })).toHaveCount(0);
  await page.locator('#sql').fill("SELECT id, nome FROM pecas WHERE estado='funcionando';");
  await page.getByRole('button', { name: 'Testar seleção' }).click();
  await expect(page.locator('.feedback')).toContainText('O rádio funciona, mas não ilumina a feira.');
  await page.locator('#sql').fill(SOLUTION_SQL);
  await page.reload();
  await expect(page.locator('#sql')).toHaveValue(SOLUTION_SQL);
  await page.getByRole('button', { name: 'Testar seleção' }).click();
  await expect(page.getByRole('heading', { name: 'Pronto para levar!' })).toBeVisible();
  await expect(page.locator('.world-part.chosen')).toHaveCount(2);
  await page.getByRole('button', { name: 'Enviar drone' }).click();
  await page.getByRole('button', { name: 'Pausar jogo', exact: true }).click();
  const before = await page.evaluate(() => localStorage.getItem('porto-sucata:save:v1'));
  await page.waitForTimeout(2600);
  expect(await page.evaluate(() => localStorage.getItem('porto-sucata:save:v1'))).toBe(before);
  await page.getByRole('button', { name: 'Continuar jogando' }).click();
  await expect(page.getByRole('heading', { name: 'Feira iluminada!' })).toBeVisible({ timeout: 10000 });
  expect(await page.evaluate(() => window.scrollY)).toBeLessThan(100);
  await expect(page.locator('.world')).toHaveClass(/lit/);
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Feira iluminada!' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});

test('syntax error, hints, tabs and non-destructive inspection', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Usar bancada' }).click();
  await page.locator('#sql').fill('SELECT banana FROM pecas;');
  await page.getByRole('button', { name: 'Testar seleção' }).click();
  await expect(page.getByRole('alert')).toContainText('A coluna banana não existe');
  await expect(page.locator('#sql')).toHaveValue('SELECT banana FROM pecas;');
  await page.getByRole('tab', { name: 'Dados', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Catálogo · tabela pecas' })).toBeVisible();
  await page.getByRole('tab', { name: 'Código', exact: true }).click();
  await page.getByRole('button', { name: 'Pedir uma pista' }).click();
  await page.getByRole('button', { name: 'Outra pista' }).click();
  await page.getByRole('button', { name: 'Outra pista' }).click();
  await page.getByRole('button', { name: 'Experimentar esta solução' }).click();
  await expect(page.locator('#sql')).toHaveValue(SOLUTION_SQL);
  await page.getByRole('button', { name: 'Manual', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
});
