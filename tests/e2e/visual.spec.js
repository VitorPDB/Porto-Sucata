import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { SOLUTION_SQL } from '../../src/mission.js';

test('capture desktop and mobile interaction states without overflow', async ({ page }) => {
  await mkdir('.impeccable/review', { recursive: true });
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.goto('/');
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: '.impeccable/review/desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '.impeccable/review/mobile.png', fullPage: true });
  await page.setViewportSize({ width: 360, height: 800 });
  await page.screenshot({ path: '.impeccable/review/user-360.png', fullPage: true });
  await page.getByRole('button', { name: 'Conversar com o feirante' }).click();
  await expect(page.locator('.actor.merchant')).toHaveClass(/selected/);
  await page.screenshot({ path: '.impeccable/review/mobile-merchant.png', fullPage: true });
  await page.getByRole('button', { name: 'Usar bancada', exact: true }).click();
  await page.locator('#sql').fill(SOLUTION_SQL);
  await page.getByRole('button', { name: 'Testar seleção' }).click();
  await expect(page.getByRole('heading', { name: 'Pronto para levar!' })).toBeVisible();
  await page.screenshot({ path: '.impeccable/review/mobile-terminal.png', fullPage: true });
  await page.setViewportSize({ width: 320, height: 740 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.screenshot({ path: '.impeccable/review/desktop-terminal.png', fullPage: true });
  await page.getByRole('button', { name: 'Enviar drone' }).click();
  await expect(page.getByRole('heading', { name: 'Feira iluminada!' })).toBeVisible({ timeout: 10000 });
  await page.screenshot({ path: '.impeccable/review/desktop-complete.png', fullPage: true });
  await page.setViewportSize({ width: 360, height: 800 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: '.impeccable/review/mobile-complete.png', fullPage: true });
});
